from typing import TypedDict, Dict, Any, List


class DebuggingState(TypedDict, total=False):

    # ========================================================
    # USER INPUT
    # ========================================================

    error_message: str
    code: str


    # ========================================================
    # CLASSIFICATION
    # ========================================================

    classification: Dict[str, Any]


    # ========================================================
    # ANALYSIS
    # ========================================================

    analysis: Dict[str, Any]


    # ========================================================
    # RAG
    # ========================================================

    rag_context: str

    retrieved_documents: List[Dict[str, Any]]


    # ========================================================
    # SUPERVISOR / AGENT ROUTING
    # ========================================================

    selected_agent: str

    routing_reason: str


    # ========================================================
    # SPECIALIST AGENT
    # ========================================================

    specialist_analysis: Dict[str, Any]


    # ========================================================
    # DEBUGGING TOOL
    # ========================================================

    tool_route: Dict[str, Any]

    tool_result: Dict[str, Any]


    # ========================================================
    # SOLUTION
    # ========================================================

    solution: Dict[str, Any]


    # ========================================================
    # VERIFICATION
    # ========================================================

    verification: Dict[str, Any]


    # ========================================================
    # CONTROL
    # ========================================================

    retry_count: int

    status: str


    # ========================================================
    # FINAL RESPONSE
    # ========================================================

    final_answer: str